import test from 'node:test';
import assert from 'node:assert/strict';
import { withApp } from '../helpers/mysql-app.js';
import { repositoryDatabase } from '../helpers/mysql-repository.js';
import { emptyLineup } from '../../src/domain/lineups.js';
import { emptyLineupOb, lineupObRows, validateLineupOb } from '../../src/domain/lineup-ob.js';
import { lineupImageData } from '../../src/domain/lineup-image.js';

test('OB free text saves atomically with lineup versions, preserves table ID, retries and archived image snapshots', async () => withApp(async ({ repository, request, admin }) => {
  const event = await repository.createEvent({ title: 'OB', type: 'scrimmage', dates: ['2099-01-01'], requestId: 'ob-event' });
  const other = await repository.createEvent({ title: 'other', type: 'guild_war', dates: ['2099-01-02'], requestId: 'other-event' });
  const ob = { ...emptyLineupOb(), enabled: 'on', attackMode: 'double', defenseMode: 'double', attack: '外部指揮甲', mobile: '外部指揮乙', defense12: '防守甲', defense34: '防守乙' };
  const input = { eventId: event.id, eventRevision: event.revision, expectedVersion: 0, requestId: 'ob-save', teams: emptyLineup(), ob };
  assert.equal((await request('/lineups/confirm', 'POST', input)).status, 401);
  const manager = await admin();
  const response = await manager.request('/lineups/confirm', 'POST', input);
  assert.equal(response.status, 201);
  const saved = (await response.json()).version;
  assert.deepEqual(saved.ob, ob);
  const db = repositoryDatabase(repository);
  const [row] = await db.query('SELECT * FROM event_lineup_ob WHERE event_id=?', [event.id]);
  assert.ok(row.id);assert.equal(row.attack, ob.attack);
  assert.ok(Object.values(row).every(value => typeof value === 'string'));
  assert.deepEqual((await repository.confirmLineup(input)), saved);
  assert.equal((await db.query('SELECT * FROM event_lineup_ob')).length, 1);
  await assert.rejects(repository.confirmLineup({ ...input, ob: { ...ob, attack: 'changed' } }), { code: 'REQUEST_CONFLICT' });
  await assert.rejects(repository.confirmLineup({ ...input, requestId: 'stale', ob: { ...ob, attack: 'changed' } }), { code: 'LINEUP_CONFLICT' });
  assert.equal((await db.query('SELECT attack FROM event_lineup_ob'))[0].attack, ob.attack);
  assert.equal((await repository.getLineupCurrent(other.id)).versions.length, 0);
  const secondOb = { ...ob, attackMode: 'single', defenseMode: 'single' };
  const second = await repository.confirmLineup({ ...input, requestId: 'second', expectedVersion: 1, ob: secondOb });
  assert.equal((await db.query('SELECT id FROM event_lineup_ob'))[0].id, row.id);
  assert.equal(lineupObRows(second.ob).flat().length, 2);
  assert.equal(lineupObRows(second.ob)[1][0].label, '防守');
  assert.equal(second.ob.mobile, ob.mobile, 'hidden text survives mode switches');
  const disabled = await repository.confirmLineup({ ...input, requestId: 'off', expectedVersion: 2, ob: { ...secondOb, enabled: 'off' } });
  assert.deepEqual(lineupObRows(disabled.ob), []);
  assert.deepEqual((await repository.getLineupCurrent(event.id)).versions[0].ob, disabled.ob);
  const image = lineupImageData({ event, teams: saved.teams, snapshots: true, ob: saved.ob, status: '已儲存' });
  assert.equal(image.obRows.flat().length, 4);
  const { ob: _omitted, ...legacyInput } = input;
  const legacySaved = await repository.confirmLineup({ ...legacyInput, requestId: 'legacy-save', expectedVersion: 3 });
  assert.deepEqual(legacySaved.ob, disabled.ob, 'older clients preserve the stored OB settings');
  const transaction = db.transaction.bind(db);
  db.transaction = (work, options) => transaction(connection => work({ ...connection, async query(sql, args) {
    if (sql.includes('INSERT INTO event_lineup_ob')) throw new Error('synthetic OB write failure');
    return connection.query(sql, args);
  } }), options);
  await assert.rejects(repository.confirmLineup({ ...input, requestId: 'rollback-ob', expectedVersion: 4 }), /synthetic OB write failure/);
  db.transaction = transaction;
  assert.equal((await repository.getLineupCurrent(event.id)).versions[0].version, 4);
  assert.equal((await db.query('SELECT enabled FROM event_lineup_ob'))[0].enabled, 'off');
  await repository.deleteEvent(event.id, event.revision);
  const archived = await repository.getLineupCurrent(event.id);
  assert.equal(archived.event.archived, true);
  assert.deepEqual(archived.versions[0].ob, disabled.ob);
  assert.deepEqual((await repository.getLineupHistory(event.id)).versions.at(-1).ob, ob);
  for (const bad of [{ ...ob, attack: 'x'.repeat(65) }, { ...ob, mobile: 'a\nb' }, { ...ob, enabled: true }, { ...ob, attackMode: 'bad' }, { ...ob, extra: 'bad' }])
    assert.throws(() => validateLineupOb(bad), { code: 'LINEUP_INVALID' });
}));
